"""Print every task prompt with its answer and named mistakes (Markdown)."""
from .tasks import ALL
from .grader import describe
print("# BillBench tasks (full prompts, answers, simulated mistakes)\n")
print("Generated by `python3 -m billbench.dump_tasks`. All data is synthetic.\n")
for t in ALL:
    print(f"## {t['id']} ({t['suite']}): {t['title']}\n")
    print(f"**Rule under test:** {t['trap']}  \n**Correct answer:** ${t['answer']:,.2f}")
    if t.get("source"):
        print(f"  \n**Source:** {t['source']}")
    print("\n**Named mistakes the grader recognizes:**\n")
    for m, v in t["mistake_values"].items():
        print(f"- ${float(v):,.2f}: {describe(m, t)}")
    print("\n<details><summary>Prompt</summary>\n\n```text\n" + t["prompt"] + "\n```\n</details>\n")
